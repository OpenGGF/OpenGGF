#!/usr/bin/env python3
"""Regenerate the Claude Code skill mirror from the canonical skill tree.

Purpose: `.agents/skills/` is the only tree authors edit. Claude Code does not
discover `.agents/skills/` itself, and a committed `.claude/skills` symlink is
unreliable on Windows checkouts without `core.symlinks`, so `.claude/skills/`
is a generated byte-for-byte copy.

Usage:
    python3 tools/git/sync_skills.py          # rewrite .claude/skills/ to match
    python3 tools/git/sync_skills.py --check  # exit 1 and list drift, change nothing

Inputs: the working tree under the repository root (or --root). The commit
hooks check the staged index separately; `--check` covers the working tree.
Origin: feature/ai-agents-md-canonical (2026-11-03), replacing hand mirroring.
"""

from __future__ import annotations

import argparse
import filecmp
import shutil
import sys
from pathlib import Path

CANONICAL = Path('.agents/skills')
MIRROR = Path('.claude/skills')


def _files(base: Path) -> set[Path]:
    if not base.is_dir():
        return set()
    return {p.relative_to(base) for p in base.rglob('*') if p.is_file() or p.is_symlink()}


def drift(root: Path) -> list[str]:
    """Return human-readable differences between the canonical tree and its mirror."""
    source, mirror = root / CANONICAL, root / MIRROR
    if mirror.is_symlink():
        return [f'{MIRROR} is a symlink; it must be a generated directory']
    wanted, present = _files(source), _files(mirror)
    problems = [f'missing {MIRROR / p}' for p in sorted(wanted - present)]
    problems += [f'extra {MIRROR / p}' for p in sorted(present - wanted)]
    problems += [f'differs {MIRROR / p}' for p in sorted(wanted & present)
                 if not filecmp.cmp(source / p, mirror / p, shallow=False)]
    return problems


def sync(root: Path) -> list[str]:
    """Make the mirror an exact copy of the canonical tree; return what changed."""
    changes = drift(root)
    if not changes:
        return []
    mirror = root / MIRROR
    if mirror.is_symlink() or mirror.is_file():
        mirror.unlink()
    elif mirror.exists():
        shutil.rmtree(mirror)
    shutil.copytree(root / CANONICAL, mirror, symlinks=False)
    return changes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='report drift without writing')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args(argv)
    if not (args.root / CANONICAL).is_dir():
        print(f'{CANONICAL} not found under {args.root}', file=sys.stderr)
        return 2
    if args.check:
        problems = drift(args.root)
        for line in problems:
            print(line)
        if problems:
            print('run python3 tools/git/sync_skills.py and stage .claude/skills/', file=sys.stderr)
        return 1 if problems else 0
    for line in sync(args.root):
        print(f'synced: {line}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
