#!/usr/bin/env python3
"""Generate the Sonic CD Time Attack catalogue: where the labelled tables of ATTACK.MMD lie.

Purpose: the Time Attack menu (game/soniccd/timeattack) reads its art, maps, palettes and tables from
ATTACK.MMD on the user's disc. The program references most of its data by absolute address in its
fixed load area (MMD origin $FF2000, Word RAM $200000), which the reader resolves through the MMD
header; the tables it reaches through labels are assembled here from the pinned source
(Time Attack/Main.asm) and located as exactly one match in the disc file. Output: offsets only.

Inputs: the user's USA disc and scddisasm at 1ecc5f3af7cc.
Output: src/main/resources/soniccd/timeattack-assets.tsv (or --check against it).
Origin: lane TA (Time Attack and backup RAM) of the 2026-11-12 Sonic CD re-host.

    python3 -I tools/soniccd/timeattack_catalogue.py --media-root ~/Downloads/Sonic-CD/media \
        --source <scddisasm checkout> [--check]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from retail_profiles import parse_cue  # noqa: E402
from stage_inventory import RawIso, Source, assemble_dc, dc_region, require, unique  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "src/main/resources/soniccd/timeattack-assets.tsv"
MAIN = "Time Attack/Main.asm"

# (asset, label, leading instruction bytes the disassembly shows as code before the dc block)
LABELS = [
    ("timeDigitTileMap", "TimeAttack_TimeDigitTileMap", b""),
    ("timeRecordTileMap", "TimeAttack_TimeRecordTileMap", b""),
    ("transferDispatch", "TimeAttack_VIntTransferDispatchTable", b""),
    # VIntTileAnimationData: its first long reads as `ori.b #$e,d0` (0000 000E) in the listing.
    ("tileAnimationData", "TimeAttack_VIntTileAnimationData", bytes.fromhex("0000000E")),
]


def block(source: Source, label: str, lead: bytes) -> bytes:
    """The straight dc.b/dc.l lines after a label (the label line itself may carry the first dc)."""
    parts = re.split(r"\n[ \t]*" + re.escape(label) + r":", source.text(MAIN), maxsplit=1)
    require(len(parts) == 2, f"{label} not in {MAIN}")
    text = parts[1]
    lines = []
    skip = 1 if lead else 0                    # the one instruction line `lead` stands for
    for raw in text.splitlines():
        line = raw.split(";", 1)[0].strip()
        if not line:
            continue
        if not line.startswith("dc."):
            if skip:
                skip -= 1
                continue
            break
        lines.append(line)
    _, entries, _ = dc_region("\n".join(lines))
    require(bool(entries), f"No data after {label}")
    return lead + assemble_dc(entries, {})


def generate(media_root: Path, source_root: Path) -> str:
    source = Source(source_root)
    cues = sorted((media_root / "USA").glob("*.cue"))
    require(len(cues) == 1, "Expected one USA CUE")
    track = (cues[0].parent / parse_cue(cues[0].read_text())[0]["file"]).resolve()
    lines = ["# Generated by tools/soniccd/timeattack_catalogue.py from the USA disc and scddisasm "
             "1ecc5f3af7ccfbe26c6c58c96e6e5bcfdd15d6ff; file offsets and lengths (hex) only.",
             "file\tname\toffset\tlength\tsource"]
    with RawIso(track) as disc:
        image = disc.file("ATTACK.MMD;1")
        for name, label, lead in LABELS:
            blob = block(source, label, lead)
            offset = unique(image, blob, name)
            lines.append(f"ATTACK.MMD;1\t{name}\t{offset:X}\t{len(blob):X}\t{MAIN} {label}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--media-root", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True, help="scddisasm checkout at the pin")
    parser.add_argument("--check", action="store_true", help="fail if the committed resource differs")
    args = parser.parse_args()
    text = generate(args.media_root.expanduser(), args.source.expanduser())
    if args.check:
        require(OUTPUT.read_text() == text, f"{OUTPUT} is stale; regenerate it")
        print(f"OK: {OUTPUT.relative_to(ROOT)} matches the disc")
        return
    OUTPUT.write_text(text)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(text.splitlines()) - 2} assets)")


if __name__ == "__main__":
    main()
