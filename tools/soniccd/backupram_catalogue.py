#!/usr/bin/env python3
"""Generate the Sonic CD backup-RAM catalogue: where the initial save data and the save layout lie.

Purpose: the backup-RAM owners (game/soniccd/backupram) read the initial Time Attack tables and the
initial main save data that InitSaveData copies (Backup RAM/Main CPU Functions.asm:223-244) from the
user's disc, and size the save record from the rs layout in _Include/Backup RAM.inc:36-55. Each blob is
assembled from the pinned scddisasm source (Backup RAM/Initial Data.asm) and located as exactly one
match in BRAMINIT.MMD on the disc. The output holds offsets, lengths and layout sizes, never disc bytes.

Inputs: the user's USA disc (CUE + split MODE1/2352 data track) and scddisasm at 1ecc5f3af7cc.
Output: src/main/resources/soniccd/backupram-assets.tsv (or --check against it).
Origin: lane TA (Time Attack and backup RAM) of the 2026-11-12 Sonic CD re-host.

    python3 -I tools/soniccd/backupram_catalogue.py --media-root ~/Downloads/Sonic-CD/media \
        --source <scddisasm checkout> [--check]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from retail_profiles import parse_cue  # noqa: E402
from stage_inventory import RawIso, Source, literal_data, require, rs_symbols, unique  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "src/main/resources/soniccd/backupram-assets.tsv"
INC = "_Include/Backup RAM.inc"
DATA = "Backup RAM/Initial Data.asm"


def layout(source: Source) -> dict[str, int]:
    """The 'Backup RAM data' rs block of Backup RAM.inc (rsreset .. BURAMDATASZ)."""
    text = source.text(INC)
    block = text.split("; Backup RAM data", 1)[1].split("; Backup RAM function parameters", 1)[0]
    body = "\n".join(line for line in block.splitlines() if not line.lstrip().startswith(";") and "---" not in line)
    values = rs_symbols(body)
    for name in ("svTmAtkTimes", "svTmAtkNames", "svTmAtkDefName", "BURAMTIMESZ", "svZone", "svTmAtkUnlock",
                 "svUnknown", "svGoodFutures", "svTitleFlags", "svSpecStage", "svTimeStones", "BURAMMAINSZ",
                 "BURAMDATASZ"):
        require(name in values, f"{INC}: {name} not declared")
    return values


def initial_data(source: Source, sizes: dict[str, int]) -> tuple[bytes, bytes]:
    """BuRAMTimeAttack (all straight dc.b) and BuRAMMain (dc.b, then dcb.b BURAMMAINSZ-(*-BuRAMMain), $00)."""
    text = source.text(DATA)
    times_text, main_text = text.split("BuRAMMain:", 1)
    times, _, _, _ = literal_data(times_text.split("BuRAMTimeAttack:", 1)[1])
    require(len(times) == sizes["BURAMTIMESZ"], f"BuRAMTimeAttack is {len(times)} bytes, BURAMTIMESZ {sizes['BURAMTIMESZ']}")
    head, tail = re.split(r"^\s*dcb\.b\s+BURAMMAINSZ-\(\*-BuRAMMain\),\s*\$00\s*$", main_text, maxsplit=1, flags=re.M)
    require(not tail.split(";")[0].strip().replace("-", ""), "Unexpected data after BuRAMMain's dcb")
    # The assembler's %binary literals (dc.b %00010000) as hexadecimal for the dc evaluator.
    head = re.sub(r"%([01]+)", lambda m: f"${int(m[1], 2):X}", head)
    main, _, _, _ = literal_data(head)
    require(len(main) <= sizes["BURAMMAINSZ"], "BuRAMMain longer than BURAMMAINSZ")
    return times, main + bytes(sizes["BURAMMAINSZ"] - len(main))


def generate(media_root: Path, source_root: Path) -> str:
    source = Source(source_root)
    sizes = layout(source)
    times, main = initial_data(source, sizes)
    cues = sorted((media_root / "USA").glob("*.cue"))
    require(len(cues) == 1, "Expected one USA CUE")
    track = (cues[0].parent / parse_cue(cues[0].read_text())[0]["file"]).resolve()
    lines = ["# Generated by tools/soniccd/backupram_catalogue.py from the USA disc and scddisasm "
             "1ecc5f3af7ccfbe26c6c58c96e6e5bcfdd15d6ff; file offsets, lengths and layout sizes (hex) only.",
             "file\tname\toffset\tlength\tsource"]
    with RawIso(track) as disc:
        init = disc.file("BRAMINIT.MMD;1")
        for name, blob, label in (("initialTimeAttack", times, "BuRAMTimeAttack"), ("initialMain", main, "BuRAMMain")):
            offset = unique(init, blob, name)
            lines.append(f"BRAMINIT.MMD;1\t{name}\t{offset:X}\t{len(blob):X}\t{DATA} {label}")
    for name in ("svTmAtkTimes", "svTmAtkNames", "svTmAtkDefName", "BURAMTIMESZ", "svZone", "svTmAtkUnlock",
                 "svUnknown", "svGoodFutures", "svTitleFlags", "svSpecStage", "svTimeStones", "BURAMMAINSZ",
                 "BURAMDATASZ"):
        lines.append(f"layout\t{name}\t{sizes[name]:X}\t0\t{INC}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--media-root", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True, help="scddisasm checkout at the pin")
    parser.add_argument("--check", action="store_true", help="fail if the committed resource differs")
    args = parser.parse_args()
    text = generate(args.media_root.expanduser(), args.source.expanduser())
    if args.check:
        require(OUTPUT.read_text() == text, f"{OUTPUT} is stale; regenerate it")
        print(f"OK: {OUTPUT.relative_to(ROOT)} matches the disc")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(text.splitlines()) - 2} entries)")


if __name__ == "__main__":
    main()
