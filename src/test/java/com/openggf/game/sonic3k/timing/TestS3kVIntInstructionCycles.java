package com.openggf.game.sonic3k.timing;

import com.openggf.data.Rom;
import com.openggf.game.sonic3k.timing.S3kVIntInstructionCycles.Input;
import com.openggf.game.sonic3k.timing.S3kVIntInstructionCycles.MissingInput;
import com.openggf.game.sonic3k.timing.S3kVIntInstructionCycles.Term;
import com.openggf.tests.RomTestUtils;
import org.junit.jupiter.api.Test;

import java.io.BufferedReader;
import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

/**
 * The adopted closed form against the frozen R9 ROM walk over 1,920 states (source oracle: the walk's own GPGX-costed
 * instruction path, generated by kos-consumer-java/slice5/export_vint8_grid.py; no native data), and the ROM pins.
 */
class TestS3kVIntInstructionCycles {
    private static final int[] KOS = {-1, 0x1C42, 0x1C1E, 0x1CFA};

    private static List<Integer> grid() throws IOException {
        List<Integer> values = new ArrayList<>();
        try (InputStream in = TestS3kVIntInstructionCycles.class.getResourceAsStream(
                "/timing/s3k-vint8-closed-handler-grid-v1.txt")) {
            assertNotNull(in, "fixture resource");
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.startsWith("#") || line.isBlank()) {
                    continue;
                }
                for (String value : line.trim().split("\\s+")) {
                    values.add(Integer.parseInt(value));
                }
            }
        }
        return values;
    }

    @Test
    void closedFormEqualsTheRomWalkOnEveryGridState() throws IOException {
        List<Integer> expected = grid();
        assertEquals(1920, expected.size());
        int index = 0;
        StringBuilder mismatches = new StringBuilder();
        for (boolean pal : new boolean[] {false, true}) {
            for (int dma : new int[] {0, 1, 2, 17, 18}) {
                for (int kos : KOS) {
                    for (boolean flash : new boolean[] {false, true}) {
                        for (boolean full : new boolean[] {false, true}) {
                            for (boolean water : new boolean[] {false, true}) {
                                for (int hInt : new int[] {0x40, 0x5C, 0xFF}) {
                                    for (int demo : new int[] {0, 5}) {
                                        int cycles = S3kVIntInstructionCycles.cycles(new Input(pal, dma, kos >= 0,
                                                kos, flash, full, water, hInt, demo));
                                        if (cycles != expected.get(index) && mismatches.length() < 800) {
                                            mismatches.append(String.format(" [%d pal=%b dma=%d kos=%X flash=%b full=%b"
                                                    + " water=%b hInt=%X demo=%d: %d vs walk %d]", index, pal, dma,
                                                    kos, flash, full, water, hInt, demo, cycles, expected.get(index)));
                                        }
                                        index++;
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
        assertEquals("", mismatches.toString());
    }

    @Test
    void pinsMatchTheShippedRomAndRefuseAnyOther() throws IOException {
        File file = RomTestUtils.ensureSonic3kRomAvailable();
        assumeTrue(file != null, "S3K ROM not available (set -Ds3k.rom.path)");
        byte[] rom;
        try (Rom r = new Rom()) {
            assertTrue(r.open(file.getAbsolutePath()));
            rom = r.readAllBytes();
        }
        assertTrue(S3kVIntInstructionCycles.romMatches(rom));
        assertTrue(S3kVIntInstructionCycles.romMatches(java.util.Arrays.copyOf(rom, 0x4E810)),
                "The production profile supplies exactly the supported prefix");
        assertFalse(S3kVIntInstructionCycles.romMatches(java.util.Arrays.copyOf(rom, 0x4E80F)),
                "A truncated routine-0 return cannot authenticate the supported code");
        byte[] other = rom.clone();
        other[0x5BC] ^= 0x01;   // the PAL delay's dbf
        assertFalse(S3kVIntInstructionCycles.romMatches(other));
        assertFalse(S3kVIntInstructionCycles.romMatches(new byte[0x1000]), "short image");
    }

    @Test
    void refusesChangedPalDelayOperandEvenWhenItsOpcodeIsIntact() throws IOException {
        byte[] original = originalRom();
        byte[] changed = original.clone();
        changed[0x5BB] ^= 1; // move.w #$700,d0 immediate, not the pinned dbf opcode.
        assertFalse(S3kVIntInstructionCycles.romMatches(changed),
                "A changed DBF iteration count cannot retain the fixed PAL cycle term");
    }

    @Test
    void refusesChangedCallTargetEvenWhenItsOpcodeIsIntact() throws IOException {
        byte[] original = originalRom();
        byte[] changed = original.clone();
        changed[0x925] ^= 2; // absolute target operand following jsr at $920.
        assertFalse(S3kVIntInstructionCycles.romMatches(changed),
                "A different callee cannot inherit the supported instruction accounting");
    }

    private static byte[] originalRom() throws IOException {
        File file = RomTestUtils.ensureSonic3kRomAvailable();
        assumeTrue(file != null, "S3K ROM not available (set -Ds3k.rom.path)");
        try (Rom rom = new Rom()) {
            assertTrue(rom.open(file.getAbsolutePath()));
            return rom.readAllBytes();
        }
    }

    @Test
    void aFigureExistsExactlyWhenNoInputIsMissing() {
        Term refused = Term.refused(Set.of(MissingInput.KOS_BUSY_PC_UNKNOWN));
        assertEquals(-1, refused.closedHandlerCycles());
        assertEquals(3, refused.unpricedCallees().size(), "DrawLevel, UpdateHUD, Process_Nem_Queue_2 stay unpriced");
        assertThrows(IllegalArgumentException.class, () -> new Term(1804, Set.of(MissingInput.REGION_UNKNOWN),
                Set.of()));
        assertThrows(IllegalArgumentException.class, () -> new Term(-1, Set.of(), Set.of()));
        assertThrows(IllegalArgumentException.class, () -> new Input(false, 19, false, 0, false, false, false, 0, 0));
    }
}
