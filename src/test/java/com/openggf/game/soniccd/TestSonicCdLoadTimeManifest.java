/**
 * Sonic CD's normal-play load-time manifest ({@code load-time-profiles/soniccd-v1.json}, its FAST copy, generated by
 * {@code tools/soniccd/load_time_manifest.py}) and the stage load it paces ({@link CdLoadTiming},
 * {@link CdLevelVIntCounter}).
 *
 * <p>Native: physics {@code vblank_counter} on row 0 is {@code levelVIntCounter} after the load and iteration 1's V-INT
 * (Level/Main.asm:182-335). Normal play (no replay seed, {@code FAST}) must start the stage from the measured load and
 * then equal native on every row where the counter advanced, up to the trace's first lost V-INT (as
 * {@code TestSonicCdStageEntryVIntBase} compares the replay seed). {@code NONE} keeps the old base 0.
 */
class TestSonicCdLoadTimeManifest {
    @TempDir
    Path tempDir;

    /** The generator's encoding equals {@link HardwareSubmissionFingerprint}'s: the value is the Python tool's. */
    @Test
    void generatorFingerprintEncodingMatchesTheEngine() {
        var submission = new HardwareWorkSubmission(HardwareWorkKind.KOS_MODULE_QUEUE, 1, 2, 3, 4, "x", 5, false,
                new com.openggf.game.timing.HardwareWorkPreparation() {
                    public boolean stepOneWorkUnit() { return false; }
                    public boolean isPrepared() { return true; }
                    public byte[] preparedPayload() { return new byte[0]; }
                    public com.openggf.game.timing.HardwareWorkPreparationSnapshot snapshot() { return null; }
                    public void restore(com.openggf.game.timing.HardwareWorkPreparationSnapshot s) { }
                });
        // python3 -c "import load_time_manifest as m; print(m.fingerprint('KOS_MODULE_QUEUE',1,2,3,4,'x',5))"
        assertEquals("sha256:f6edb851db3c22f068f4e291cb814b6c1cfba97ddf8dd8007ed7ab14c37a472d",
                HardwareSubmissionFingerprint.compute(submission));
    }

    /** Both manifests parse; the FAST copy starts as the measured entries (it may be tuned later, S3K's precedent). */
    @Test
    void manifestsLoadAndFastStartsAsTheMeasuredEntries() throws Exception {
        var mapper = new ObjectMapper();
        try (InputStream measured = resource(SonicCdGameModule.PROFILED_LOAD_TIME_MANIFEST);
             InputStream fast = resource(SonicCdGameModule.FAST_LOAD_TIME_MANIFEST)) {
            var m = mapper.readTree(measured);
            var f = mapper.readTree(fast);
            assertEquals(m.get("entries"), f.get("entries"));
            assertEquals(75, m.get("entries").size(), "70 fresh stage entries, checkpoint, warp arrival, three videos");
        }
        for (String name : List.of(SonicCdGameModule.PROFILED_LOAD_TIME_MANIFEST, SonicCdGameModule.FAST_LOAD_TIME_MANIFEST)) {
            try (InputStream in = resource(name)) {
                ProfiledLoadTimeManifest.load(in, warning -> { });
            }
        }
        assertTrue(new SonicCdGameModule().createLoadTimeProfile(LoadTimeSimulationMode.NONE, w -> { })
                == com.openggf.game.timing.LoadTimeProfile.IMMEDIATE);
    }

    /** One stage per zone, normal play: the measured load base, then native on every compared row. */
    @ParameterizedTest(name = "{0}")
    @ValueSource(strings = {"R11A", "R31A", "R41A", "R51A", "R61A", "R71A", "R81A"})
    void normalPlayStageLoadEqualsNative(String stage) throws Exception {
        Run run = replay(CdStagePayload.valueOf(stage), "FAST");
        System.out.println("[scd-load-time] " + stage + " FAST: row 0 engine " + run.rowZero() + " native "
                + run.nativeRowZero() + "; compared " + run.compared() + ", mismatches " + run.mismatches().size()
                + " " + run.mismatches().stream().limit(3).toList());
        assertEquals(run.nativeRowZero(), run.rowZero(), "row 0's levelVIntCounter");
        assertTrue(run.compared() > 400, "too few rows compared: " + run.compared());
        assertEquals(List.of(), run.mismatches(), "levelVIntCounter against native");
    }

    /** {@code NONE}: today's behaviour, base 0, so row 0 shows iteration 1's V-INT alone. */
    @Test
    void noneKeepsTheBaseAtZero() throws Exception {
        Run run = replay(CdStagePayload.R11A, "NONE");
        assertEquals(1, run.rowZero(), "NONE: .ClearFlowers' clear plus iteration 1's V-INT");
    }

    private record Run(int rowZero, int nativeRowZero, int compared, List<String> mismatches) { }

    private Run replay(CdStagePayload payload, String mode) throws Exception {
        Path root = CdTestMedia.nativeFile("rehost-fixtures/README.md").getParent();
        var fixture = CdFixtureReplay.Fixture.under(root, payload);
        Assumptions.assumeTrue(fixture.present(), "Native fixture absent: " + payload);
        TraceData trace = TraceData.load(fixture.traceDir());
        List<String> mismatches = new ArrayList<>();
        int[] compared = {0};
        int[] rowZero = {-1};
        try (CdDiscDataSource disc = CdDiscDataSource.open(CdTestMedia.usaCue())) {
            CdFixtureReplay.replay(disc, Files.createDirectories(tempDir.resolve(payload.name() + mode)), fixture,
                    trace.frameCount() - 1, false, -1, -1, new CdFixtureReplay.Hooks() {
                        @Override public String productionLoadTime() { return mode; }

                        @Override public void row(int row, AbstractPlayableSprite sonic) {
                            int engine = GameServices.level().getObjectManager().getVblaCounter() & 0xFFFF;
                            if (row == 0) rowZero[0] = engine;
                            boolean finished = row == 0
                                    || trace.getFrame(row).vblankCounter() != trace.getFrame(row - 1).vblankCounter();
                            if (!finished) return;
                            compared[0]++;
                            int nativeCounter = trace.getFrame(row).vblankCounter();
                            if (engine != nativeCounter) mismatches.add("row " + row + " native " + nativeCounter + " engine " + engine);
                        }
                    });
        }
        return new Run(rowZero[0], trace.getFrame(0).vblankCounter(), compared[0], mismatches);
    }

    private static InputStream resource(String name) {
        InputStream in = SonicCdGameModule.class.getResourceAsStream(name);
        if (in == null) throw new IllegalStateException("missing " + name);
        return in;
    }
}
