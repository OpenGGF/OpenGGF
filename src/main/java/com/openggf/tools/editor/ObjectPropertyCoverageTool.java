package com.openggf.tools.editor;

import com.openggf.level.metadata.ObjectPropertySchema;
import com.openggf.game.sonic1.objects.Sonic1ObjectProperties;
import com.openggf.game.sonic2.objects.Sonic2ObjectProperties;
import com.openggf.game.sonic3k.objects.Sonic3kObjectProperties;
import java.util.function.IntFunction;

/** Prints schema/fallback inventory; no ROM required. Origin: editor-authoring-parity, 2026-10-22. */
public final class ObjectPropertyCoverageTool {
    private ObjectPropertyCoverageTool() { }
    public static void main(String[] args) { System.out.print(report()); }
    public static String report() {
        var out = new StringBuilder("# Object property schema coverage\n\n");
        out.append("Generated by `com.openggf.tools.editor.ObjectPropertyCoverageTool` from per-game providers.\n")
                .append("Every numeric ID is listed, including reserved/unimplemented IDs. A schema describes\n")
                .append("subtype bits; it does not certify that a stock object supports authored playtests.\n")
                .append("S3K entries cover common IDs in both S3KL and SKL. Family-dependent IDs and keyed objects use raw fallback.\n")
                .append("Named fields retain unknown bits and values byte-for-byte. Unused subtype fields explicitly identify objects that ignore the byte.\n")
                .append("Numeric frames, counts and trigger indices describe ROM inputs, not a guarantee that every byte selects valid art or a safe route.\n\n");
        append(out, "Sonic 1", Sonic1ObjectProperties::schema);
        append(out, "Sonic 2", Sonic2ObjectProperties::schema);
        append(out, "Sonic 3 & Knuckles", Sonic3kObjectProperties::schema);
        return out.toString().stripTrailing() + "\n";
    }
    private static void append(StringBuilder out, String game, IntFunction<ObjectPropertySchema> provider) {
        int count = 0;
        for (int id = 0; id < 256; id++) if (!provider.apply(id).fields().isEmpty()) count++;
        out.append("## ").append(game).append("\n\n").append(count).append(" schemas; ")
                .append(256 - count).append(" raw fallbacks.\n\n| Object ID | Editing |\n|---|---|\n");
        for (int id = 0; id < 256; id++) {
            var schema = provider.apply(id);
            String description = schema.fields().isEmpty() ? "Raw fallback" : "Schema: " +
                    String.join(", ", schema.fields().stream().map(ObjectPropertySchema.Field::label).toList());
            out.append("| `%02X` | %s |\n".formatted(id, description));
        }
        out.append('\n');
    }
}
