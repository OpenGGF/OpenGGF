package com.openggf.game.soniccd;

import com.openggf.data.cd.Iso9660FileSystem;
import com.openggf.game.timing.HardwareServiceBoundary;
import com.openggf.game.timing.HardwareTimingService;
import com.openggf.game.timing.HardwareWorkHandle;
import com.openggf.game.timing.HardwareWorkKind;
import com.openggf.game.timing.HardwareWorkPreparation;
import com.openggf.game.timing.HardwareWorkPreparationSnapshot;
import com.openggf.game.timing.HardwareWorkSubmission;

import java.util.Objects;

/**
 * Sonic CD's loads as submitted work for the normal-play load-time profile ({@code gameplay.loadTimeSimulation};
 * manifests {@code load-time-profiles/soniccd-v1.json} and {@code soniccd-fast-v1.json}, generated by
 * {@code tools/soniccd/load_time_manifest.py}). The kinds are the owner-approved normal-play load kinds (contract
 * section "2026-11-13 extension: Sonic CD normal-play load kinds"); they never take a trace row's readiness.
 *
 * <p>Both loads are synchronous in the engine: the work is already done when it is submitted. What the profile
 * decides is how many V-INTs it took natively, and the owner of each load counts them: the submission is
 * activated at {@code PRE_MAIN_LOOP} (not an eligible boundary, so no V-INT is counted for it) and then serviced
 * one {@code VINT_SERVICE} at a time until the profile admits it, as {@code .WaitPLC2}'s {@code VSync} loop waits
 * (Level/Main.asm:253-259). Under {@code NONE}, or with no manifest entry, the work is ready at once: 0 V-INTs.
 */
public final class CdLoadTiming {
    /** Guard against a manifest value no load could take (the longest native stage load is 80). */
    private static final int MAX_VINTS = 3600;

    private CdLoadTiming() { }

    /**
     * A stage load: {@code LevelStart} from {@code .ClearFlowers} (Level/Main.asm:182) to {@code Level_MainLoop}'s
     * first {@code VSync} (:333-335), keyed by the stage program file (its ISO extent and byte length) and the PLC
     * list {@code LoadLevelData} queues for this entry ({@link #levelStartPlc}).
     */
    public static HardwareWorkSubmission stageLoad(Iso9660FileSystem.Entry stageFile, int plcList) {
        Objects.requireNonNull(stageFile, "stageFile");
        return new HardwareWorkSubmission(HardwareWorkKind.SCD_STAGE_LOAD, (int) stageFile.extentBlock(),
                (int) stageFile.size(), plcList, 0, "LoadLevelData", 0, false, new Ready());
    }

    /**
     * A video stream read: {@code ROMREADN} to its first sector ({@code ReadFMVSectors}, CD System Program/SP.asm:720-757),
     * keyed by the file's ISO extent and the sector count {@code FileEngine_LoadFMV} computes ({@link #sectorCount}).
     */
    public static HardwareWorkSubmission videoRead(Iso9660FileSystem.Entry streamFile) {
        Objects.requireNonNull(streamFile, "streamFile");
        return new HardwareWorkSubmission(HardwareWorkKind.CD_READ_READY, (int) streamFile.extentBlock(),
                sectorCount(streamFile.size()), 0, 0, "ROMREADN", 0, false, new Ready());
    }

    /**
     * {@code FileEngine_LoadFMV}'s {@code .GetSectors}: {@code move.l #1,feSectorCnt}, then one more for each further
     * $800 bytes ({@code subi.l #$800,d1; ble.s .ReadFile; addq.l #1,feSectorCnt}; SP.asm:691-699).
     */
    public static int sectorCount(long size) {
        int count = 1;
        long rest = size;
        while ((rest -= 0x800) > 0) count++;
        return count;
    }

    /**
     * The PLC list {@code LoadLevelData} queues (Palmtree Panic/Load Level Data.asm:37-48): with {@code spawnMode}
     * set (a checkpoint restart or a time-warp arrival) {@code LoadSectionArt}'s list for the camera's section;
     * otherwise, with the title card already loaded ({@code plcLoadFlags} bit 1), the level PLC in
     * {@code LevelDataIndex}'s fifth byte; otherwise none, 0 (the same {@code beq.s .End} a level PLC of 0 takes).
     *
     * @param sectionInitPlc {@code SectionInitPLCs} at the camera's section, or -1 where the engine does not
     *                       catalogue the stage's section table (no measurement exists for those entries)
     */
    public static int levelStartPlc(boolean spawnModeSet, boolean titleCardAlreadyLoaded, int levelDataPlc,
                                    int sectionInitPlc) {
        if (spawnModeSet) return sectionInitPlc;
        return titleCardAlreadyLoaded ? levelDataPlc : 0;
    }

    /**
     * {@code LoadSectionArt} (Section Art Load.asm:7-22): the first {@code SectionRanges} bound above {@code cameraX}
     * selects the {@code SectionInitPLCs} word; both tables follow the $FFFF-terminated range list, the update list
     * first. {@code ranges} is the stage file offset of {@code SectionRanges}, -1 when the engine has none.
     */
    public static int sectionInitPlc(byte[] stageFile, int ranges, int cameraX) {
        if (ranges < 0) return -1;
        int words = 0;
        int section = -1;
        while (true) {
            int bound = u16(stageFile, ranges + words * 2);
            if (section < 0 && (bound == 0xFFFF || (cameraX & 0xFFFF) < bound)) section = words;
            words++;
            if (bound == 0xFFFF) break;
            if (words > 32) throw new IllegalStateException("SectionRanges has no $FFFF terminator");
        }
        return u16(stageFile, ranges + 4 * words + 2 * section);
    }

    private static final java.util.Map<CdZone, String> SECTION_CATALOGUES = java.util.Map.of(
            CdZone.PALMTREE_PANIC, "ppz", CdZone.COLLISION_CHAOS, "ccz", CdZone.TIDAL_TEMPEST, "ttz",
            CdZone.QUARTZ_QUADRANT, "qqz", CdZone.WACKY_WORKBENCH, "wwz", CdZone.STARDUST_SPEEDWAY, "ssz",
            CdZone.METALLIC_MADNESS, "mmz");
    private static final java.util.Map<String, com.openggf.game.soniccd.objects.art.CdObjectTables> TABLES =
            new java.util.concurrent.ConcurrentHashMap<>();

    /**
     * The stage file offset of {@code SectionRanges} from the zone's object catalogue
     * ({@code object-catalogue-<zone>.tsv}), or -1 where the engine does not catalogue one for this stage.
     */
    public static int sectionRanges(CdStagePayload payload) {
        String owner = SECTION_CATALOGUES.get(payload.stage().zone());
        if (owner == null) return -1;
        var row = TABLES.computeIfAbsent(owner, com.openggf.game.soniccd.objects.art.CdObjectTables::load).row(payload);
        Integer offset = row == null ? null : row.get("sectionRanges");
        return offset == null ? -1 : offset;
    }

    private static int u16(byte[] data, int offset) {
        return ((data[offset] & 0xFF) << 8) | (data[offset + 1] & 0xFF);
    }

    /**
     * A program-owned timing service for a hosted program that runs outside a gameplay session (the video
     * players), with the session's normal-play profile, as the S3K title owns one for its loop. {@code null}
     * without a session: the caller keeps its documented fallback.
     */
    public static HardwareTimingService programTiming() {
        var world = com.openggf.game.session.SessionManager.getCurrentWorldSession();
        if (world == null || world.getGameModule() == null) return null;
        var profile = world.getGameModule().createLoadTimeProfile(world.loadTimeSimulationMode(), LOG::warning);
        return new HardwareTimingService(com.openggf.game.timing.RomWorkBudgetScheduler.oneWorkUnitAt(
                HardwareServiceBoundary.POST_OBJECTS), profile);
    }

    private static final java.util.logging.Logger LOG = java.util.logging.Logger.getLogger(CdLoadTiming.class.getName());

    /**
     * Submits already-done work and counts the V-INTs the profile holds it for (see the class comment). The job
     * is claimed before returning, so nothing stays pending in the ledger.
     */
    public static int vintsUntilReady(HardwareTimingService timing, HardwareWorkSubmission submission) {
        Objects.requireNonNull(timing, "timing");
        HardwareWorkHandle handle = timing.submit(submission);
        timing.service(HardwareServiceBoundary.PRE_MAIN_LOOP);
        int vints = 0;
        while (!timing.isReady(handle)) {
            if (vints == MAX_VINTS) throw new IllegalStateException("load never became ready: " + handle);
            timing.service(HardwareServiceBoundary.VINT_SERVICE);
            vints++;
        }
        timing.claim(handle);
        return vints;
    }

    /** Work the engine has already done when it submits it (boundary-driven, so the budget scheduler skips it). */
    private static final class Ready implements HardwareWorkPreparation {
        private static final byte[] NO_PAYLOAD = new byte[0];

        @Override public boolean stepOneWorkUnit() { return false; }
        @Override public boolean isPrepared() { return true; }
        @Override public byte[] preparedPayload() { return NO_PAYLOAD; }
        @Override public HardwareWorkPreparationSnapshot snapshot() { return Ready::new; }
        @Override public void restore(HardwareWorkPreparationSnapshot snapshot) {
            throw new UnsupportedOperationException("hardware timing restores by recreating preparations");
        }
        @Override public boolean isBoundaryDriven() { return true; }
    }
}
