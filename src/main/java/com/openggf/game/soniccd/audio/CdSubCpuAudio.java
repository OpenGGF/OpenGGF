package com.openggf.game.soniccd.audio;

import com.openggf.audio.presentation.AudioPresentationMixer;
import com.openggf.game.rewind.RewindSnapshottable;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;
import java.util.Objects;
import java.util.function.Supplier;

/**
 * The sub CPU's audio: the actions the CD system program takes for the audio commands stage
 * code sends with {@code SubCPUCmd} (Level/Sub CPU.asm:21-43).
 *
 * <p>The command table is {@code subcpu-audio-commands.tsv}, generated by
 * {@code tools/soniccd/subcpu_audio_catalogue.py} from the {@code .SPCmds} jump table and the
 * handlers it names (CD System Program/SPX.asm:331-544). {@code SubCPUCmd} waits for the sub CPU to finish the
 * handler, so an action takes effect at the request.
 *
 * <p>PCM commands write a byte to the PCM driver's queue ({@code PCMDrvQueue}). The driver
 * ({@link CdPcmDriver}) is the stage's bank from {@code stage-pcm-banks.tsv}, generated from
 * {@code .PCMDrivers} (SPX.asm), loaded only when it changes ({@code SPCmd_LoadLevel},
 * SPX.asm:744-772). It runs on the chip's own clock: the chip makes one sample per 384
 * sub-CPU cycles of 12.5 MHz and the driver ticks every {@link CdPcmDriver#CHIP_SAMPLES_PER_TICK}
 * chip samples, whatever the video frame does. Chip output reaches the mix by linear
 * interpolation onto the output clock, at unity gain (the native mix level is unmeasured).
 *
 * <p>The player's music and effect volumes ({@link #setMixGains}) follow what the game treats as
 * each. Music: every disc track (the stage music and every jingle the system program plays from the
 * disc), the video programs' streamed songs, and the PCM driver's song channels (the Past music).
 * Effects: the PCM channels an effect track owns ({@link CdPcmDriver#sfxChannelMask}); the FM
 * effects take theirs in the SMPS session. At unity on both the render takes the ungained path.
 */
public final class CdSubCpuAudio {
    public enum Action { CDDA_REPEAT, CDDA_ONCE, CDDA_FADE, CDDA_STOP, CDDA_PAUSE, CDDA_UNPAUSE, CDDA_RESET_VOLUME, PCM_QUEUE }

    public record Command(int id, String name, Action action, int argument) { }

    /** Rewind state of the whole owner; {@code pcm} is null before a stage loads a bank. */
    public record State(CdCddaPlayer.State cdda, int pcmQueue, PcmState pcm) {
        public State(CdCddaPlayer.State cdda, int pcmQueue) { this(cdda, pcmQueue, null); }
    }

    /** The loaded bank, its driver, the chip and the two clocks' phases. */
    public record PcmState(String bank, CdPcmDriver.State driver,
                           com.openggf.game.soniccd.device.pcm.CdPcmState chip,
                           long phase, int tickCounter, int previous, int current) { }

    private static final Map<String, String> STAGE_BANKS = loadBanks();

    private static final Map<Integer, Command> COMMANDS = load();

    private final Supplier<CdCddaPlayer.TrackSource> tracks;
    private final java.util.function.Function<com.openggf.game.soniccd.CdNativeFile, byte[]> files;
    private final com.openggf.game.soniccd.device.pcm.CdPcmDevice chip = new com.openggf.game.soniccd.device.pcm.CdPcmDevice();
    private CdPcmDriver pcm;
    private String loadedBank;
    private long pcmPhase;
    private int pcmTickCounter;
    private int pcmPrevious;
    private int pcmCurrent;
    private CdCddaPlayer cdda;
    private CdCddaPlayer.State pendingRestore = CdCddaPlayer.State.IDLE;
    private int pcmQueue;
    private int outputRate;
    /** Presentation gains, {@link AudioPresentationMixer#UNITY_GAIN} = 1; config, never rewind state. */
    private int musicGain = AudioPresentationMixer.UNITY_GAIN;
    private int sfxGain = AudioPresentationMixer.UNITY_GAIN;
    /** Test-only: take the gained paths at unity too, to show they reduce to the ungained ones. */
    private boolean gainedPathAtUnity;
    private short[] scratch = new short[0];
    private final RewindSnapshottable<State> rewind = new RewindSnapshottable<>() {
        @Override public String key() { return "soniccd-subcpu-audio"; }
        @Override public State capture() { return state(); }
        @Override public void restore(State snapshot) { CdSubCpuAudio.this.restore(snapshot); }
        @Override public void resetForMissingSnapshot() { CdSubCpuAudio.this.restore(new State(CdCddaPlayer.State.IDLE, 0)); }
    };

    public CdSubCpuAudio(Supplier<CdCddaPlayer.TrackSource> tracks) {
        this(tracks, null);
    }

    /** @param files reads one disc file whole; null leaves the PCM driver unloaded */
    public CdSubCpuAudio(Supplier<CdCddaPlayer.TrackSource> tracks,
                         java.util.function.Function<com.openggf.game.soniccd.CdNativeFile, byte[]> files) {
        this.tracks = Objects.requireNonNull(tracks, "tracks");
        this.files = files;
    }

    /**
     * {@code SPCmd_LoadLevel}'s driver load (SPX.asm:756-768): a different bank replaces the
     * driver, whose zeroed variables make its first run {@code InitDriver} (PCM/_Driver.asm:
     * 577-583, :1058-1077). That run happens here, as the native timer does during the rest
     * of the load, so a music request queued by the new stage finds an initialised driver.
     */
    public void loadStage(com.openggf.game.soniccd.CdStagePayload payload) {
        String bank = STAGE_BANKS.get(payload.name());
        if (bank == null || files == null || bank.equals(loadedBank)) return;
        com.openggf.game.soniccd.CdNativeFile file = java.util.Arrays.stream(com.openggf.game.soniccd.CdNativeFile.values())
                .filter(f -> f.isoName().equals(bank)).findFirst()
                .orElseThrow(() -> new IllegalStateException("No disc file " + bank));
        pcm = new CdPcmDriver(files.apply(file), chip);
        loadedBank = bank;
        pcm.tick();
        pcmTickCounter = 0;
    }

    /** The loaded PCM driver, or null before a stage. */
    public CdPcmDriver pcmDriver() {
        return pcm;
    }

    public static Command command(int id) {
        return COMMANDS.get(id);
    }

    /** A command's ID by its System.inc name, from the generated table. */
    public static int commandId(String name) {
        for (Command command : COMMANDS.values()) {
            if (command.name().equals(name)) return command.id();
        }
        throw new IllegalArgumentException("No sub-CPU audio command " + name);
    }

    /** Applies one sub-CPU command; returns false for a command with no audio action. */
    public boolean submit(int commandId) {
        Command command = COMMANDS.get(commandId);
        if (command == null) {
            return false;
        }
        switch (command.action()) {
            case CDDA_REPEAT -> player().play(command.argument(), true);
            case CDDA_ONCE -> player().play(command.argument(), false);
            case CDDA_FADE -> player().fadeOut();
            case CDDA_STOP -> player().stop();
            case CDDA_PAUSE -> player().setPaused(true);
            case CDDA_UNPAUSE -> player().setPaused(false);
            case CDDA_RESET_VOLUME -> player().resetVolume();
            case PCM_QUEUE -> {
                pcmQueue = command.argument();
                if (pcm != null) pcm.queue(command.argument());
            }
        }
        return true;
    }

    public void bindOutputRate(int sampleRate) {
        outputRate = sampleRate;
        if (cdda != null) cdda.bindOutputRate(sampleRate);
    }

    /** Mixes CD audio into one presentation packet on the output clock. */
    public void render(short[] target, int stereoFrames) {
        if (cdda != null) {
            if (unity(musicGain)) {
                cdda.render(target, stereoFrames);
            } else {
                cdda.render(silence(stereoFrames), stereoFrames);
                addAtMusicGain(target, stereoFrames);
            }
        }
        if (program != null) {
            if (unity(musicGain)) {
                program.render(target, stereoFrames);
            } else {
                program.render(silence(stereoFrames), stereoFrames);
                addAtMusicGain(target, stereoFrames);
            }
        } else if (pcm != null && outputRate > 0) {
            renderPcm(target, stereoFrames);
        }
    }

    /**
     * The player's music and sound-effect volumes in {@link AudioPresentationMixer#UNITY_GAIN}
     * units. Presentation only: no driver, chip or transport state depends on them, so they are
     * neither captured for rewind nor reset at a stage load.
     */
    public void setMixGains(int musicGain, int sfxGain) {
        this.musicGain = Math.clamp(musicGain, 0, AudioPresentationMixer.UNITY_GAIN);
        this.sfxGain = Math.clamp(sfxGain, 0, AudioPresentationMixer.UNITY_GAIN);
    }

    /** Test-only: whether the gained paths are taken at unity as well. */
    void gainedPathAtUnity(boolean enabled) {
        gainedPathAtUnity = enabled;
    }

    private boolean unity(int gain) {
        return gain == AudioPresentationMixer.UNITY_GAIN && !gainedPathAtUnity;
    }

    /**
     * Off unity a music source renders into this silent buffer, so its transport moves on at any
     * gain, and {@link #addAtMusicGain} adds exactly what it would have added, scaled, with the
     * same saturation.
     */
    private short[] silence(int stereoFrames) {
        int samples = stereoFrames * 2;
        if (scratch.length < samples) scratch = new short[samples];
        java.util.Arrays.fill(scratch, 0, samples, (short) 0);
        return scratch;
    }

    private void addAtMusicGain(short[] target, int stereoFrames) {
        for (int i = 0; i < stereoFrames * 2; i++) {
            target[i] = (short) Math.clamp(target[i] + ((scratch[i] * musicGain) >> 8), -32768, 32767);
        }
    }

    // --- lane END: a program that drives the PCM chip itself -------------------------------------------
    private ProgramPcm program;

    /**
     * A program that streams into the PCM chip itself: the video programs' sub-CPU files
     * (FMV/Sub (Opening).asm, Sub (Ending).asm). Their loader stops the PCM driver's timer first
     * ({@code bclr #3,GAIRQMASK}, SPX.asm:1394, 1419) and clears {@code curPCMDriver} after them
     * (SPX.asm:1411, 1436), so the stage's bank is reloaded by the next stage. The program steps the chip on
     * its own (game) clock and hands each chip sample here; {@link #render} plays the samples one game frame
     * produced across that frame's output samples.
     */
    public ProgramPcm beginProgramPcm() {
        pcm = null;                                       // timer stopped: no driver ticks while the program runs
        loadedBank = null;                                // move.l #0,curPCMDriver after the program
        program = new ProgramPcm(chip);
        return program;
    }

    /** The streaming program returned. */
    public void endProgramPcm() {
        program = null;
    }

    /**
     * {@code LoadPCMDriver} (SPX.asm:2456-2468) for the sound test's PCM commands, which load a zone's driver
     * before queueing ({@code SPCmd_TestFutureSFX} and the others, SPX.asm:2283-2450): a different file replaces
     * the driver, the same one is kept.
     */
    public void loadPcmDriver(String isoName) {
        if (files == null || isoName.equals(loadedBank)) return;
        com.openggf.game.soniccd.CdNativeFile file = java.util.Arrays.stream(com.openggf.game.soniccd.CdNativeFile.values())
                .filter(f -> f.isoName().equals(isoName)).findFirst()
                .orElseThrow(() -> new IllegalStateException("No disc file " + isoName));
        pcm = new CdPcmDriver(files.apply(file), chip);
        loadedBank = isoName;
        pcm.tick();
        pcmTickCounter = 0;
    }

    /** The chip as a streaming program drives it, with the samples it produced since the last render. */
    public static final class ProgramPcm {
        private final com.openggf.game.soniccd.device.pcm.CdPcmDevice chip;
        private int[] samples = new int[1024];
        private int count;
        private int previous;

        ProgramPcm(com.openggf.game.soniccd.device.pcm.CdPcmDevice chip) { this.chip = chip; }

        /** A port over a chip of its own, for programs run without the audio owner (tests, tools). */
        public static ProgramPcm detached() { return new ProgramPcm(new com.openggf.game.soniccd.device.pcm.CdPcmDevice()); }

        public com.openggf.game.soniccd.device.pcm.CdPcmDevice chip() { return chip; }

        /** One chip sample ({@code (left << 16) | (right & 0xffff)}, as {@code CdPcmDevice.step} returns it). */
        public void sample(int packed) {
            if (count == samples.length) {
                if (count >= 1 << 16) count = 0;          // nobody renders (no audio device): drop the backlog
                else samples = java.util.Arrays.copyOf(samples, count * 2);
            }
            samples[count++] = packed;
        }

        /** Stretch the samples produced since the last call over this output packet (linear interpolation). */
        void render(short[] target, int stereoFrames) {
            if (count == 0 || stereoFrames <= 0) return;
            for (int i = 0; i < stereoFrames; i++) {
                double position = (double) i * count / stereoFrames;
                int index = (int) position;
                double frac = position - index;
                int a = index == 0 ? previous : samples[index - 1], b = samples[Math.min(index, count - 1)];
                int l = (int) Math.round((a >> 16) + ((b >> 16) - (a >> 16)) * frac);
                int r = (int) Math.round((short) a + ((short) b - (short) a) * frac);
                target[i * 2] = (short) Math.clamp(target[i * 2] + l, -32768, 32767);
                target[i * 2 + 1] = (short) Math.clamp(target[i * 2 + 1] + r, -32768, 32767);
            }
            previous = samples[count - 1];
            count = 0;
        }
    }
    // --- end lane END

    /**
     * Steps the chip at 12500000/384 Hz against the output clock with an exact integer phase,
     * running the driver every 510 chip samples, and mixes linearly interpolated output.
     */
    private void renderPcm(short[] target, int stereoFrames) {
        long period = (long) CdPcmDriver.CHIP_RATE_DENOMINATOR * outputRate;
        boolean split = !unity(musicGain) || !unity(sfxGain);
        int sfxChannels = split ? pcm.sfxChannelMask() : 0;
        for (int i = 0; i < stereoFrames; i++) {
            pcmPhase += CdPcmDriver.CHIP_RATE_NUMERATOR;
            while (pcmPhase >= period) {
                pcmPhase -= period;
                if (++pcmTickCounter >= CdPcmDriver.CHIP_SAMPLES_PER_TICK) {
                    pcmTickCounter = 0;
                    pcm.tick();
                    if (split) sfxChannels = pcm.sfxChannelMask();
                }
                pcmPrevious = pcmCurrent;
                pcmCurrent = split ? splitSample(sfxChannels) : chip.step();
            }
            double frac = (double) pcmPhase / period;
            int l = (int) Math.round((pcmPrevious >> 16) + ((pcmCurrent >> 16) - (pcmPrevious >> 16)) * frac);
            int r = (int) Math.round((short) pcmPrevious + ((short) pcmCurrent - (short) pcmPrevious) * frac);
            target[i * 2] = (short) Math.clamp(target[i * 2] + l, -32768, 32767);
            target[i * 2 + 1] = (short) Math.clamp(target[i * 2 + 1] + r, -32768, 32767);
        }
    }

    /**
     * One chip sample with the song's channels at the music gain and the effect-owned channels at
     * the effect gain, summed and clamped as the chip clamps its own sum. At unity on both this is
     * the chip's output exactly. The interpolation pair keeps the mixed value, so a rewind restore
     * made under other gains replays at most one interpolated sample at the gains it was captured at.
     */
    private int splitSample(int sfxChannels) {
        chip.stepSplit(sfxChannels);
        int sfxLeft = chip.selectedLeft(), sfxRight = chip.selectedRight();
        int left = ((chip.sumLeft() - sfxLeft) * musicGain + sfxLeft * sfxGain) >> 8;
        int right = ((chip.sumRight() - sfxRight) * musicGain + sfxRight * sfxGain) >> 8;
        return (Math.clamp(left, -32768, 32767) << 16) | (Math.clamp(right, -32768, 32767) & 0xFFFF);
    }

    public State state() {
        PcmState pcmState = pcm == null ? null : new PcmState(loadedBank, pcm.capture(), chip.captureState(),
                pcmPhase, pcmTickCounter, pcmPrevious, pcmCurrent);
        return new State(cdda == null ? pendingRestore : cdda.state(), pcmQueue, pcmState);
    }

    public void restore(State state) {
        Objects.requireNonNull(state, "state");
        pcmQueue = state.pcmQueue();
        restorePcm(state.pcm());
        if (cdda == null && state.cdda().track() == 0) {
            pendingRestore = state.cdda();
            return;
        }
        player().restore(state.cdda());
    }

    private void restorePcm(PcmState state) {
        if (state == null) {
            return;
        }
        if (!state.bank().equals(loadedBank)) {
            loadedBank = null;
            loadStageBank(state.bank());
        }
        pcm.restore(state.driver());
        chip.restoreState(state.chip());
        pcmPhase = state.phase();
        pcmTickCounter = state.tickCounter();
        pcmPrevious = state.previous();
        pcmCurrent = state.current();
    }

    private void loadStageBank(String bank) {
        for (var entry : STAGE_BANKS.entrySet()) {
            if (entry.getValue().equals(bank)) {
                loadStage(com.openggf.game.soniccd.CdStagePayload.valueOf(entry.getKey()));
                return;
            }
        }
        throw new IllegalStateException("No stage uses PCM bank " + bank);
    }

    /** Last byte written to {@code PCMDrvQueue}; the PCM driver that would consume it is not hosted. */
    public int pcmQueue() {
        return pcmQueue;
    }

    /** One adapter instance: the registry refreshes a key only with the same subsystem. */
    public RewindSnapshottable<State> rewindAdapter() {
        return rewind;
    }

    private CdCddaPlayer player() {
        if (cdda == null) {
            cdda = new CdCddaPlayer(Objects.requireNonNull(tracks.get(), "CD audio needs the loaded disc"));
            cdda.restore(pendingRestore);
            if (outputRate > 0) cdda.bindOutputRate(outputRate);
        }
        return cdda;
    }

    private static Map<String, String> loadBanks() {
        Map<String, String> table = new HashMap<>();
        try (InputStream in = CdSubCpuAudio.class.getResourceAsStream("/soniccd/stage-pcm-banks.tsv")) {
            if (in == null) throw new IllegalStateException("stage-pcm-banks.tsv is missing");
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            for (String line; (line = reader.readLine()) != null; ) {
                if (line.isBlank() || line.startsWith("#")) continue;
                String[] f = line.split("\t");
                table.put(f[0], f[2]);
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return Map.copyOf(table);
    }

    private static Map<Integer, Command> load() {
        Map<Integer, Command> table = new HashMap<>();
        try (InputStream in = CdSubCpuAudio.class.getResourceAsStream("/soniccd/subcpu-audio-commands.tsv")) {
            if (in == null) throw new IllegalStateException("subcpu-audio-commands.tsv is missing");
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            for (String line; (line = reader.readLine()) != null; ) {
                if (line.isBlank() || line.startsWith("#")) continue;
                String[] f = line.split("\t", -1);
                int id = Integer.parseInt(f[0], 16);
                Action action = Action.valueOf(f[3].toUpperCase(java.util.Locale.ROOT));
                int argument = f[4].isEmpty() ? 0
                        : action == Action.PCM_QUEUE ? Integer.parseInt(f[4], 16) : Integer.parseInt(f[4]);
                table.put(id, new Command(id, f[1], action, argument));
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return Map.copyOf(table);
    }
}
