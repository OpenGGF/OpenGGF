package com.openggf.sprites.playable;

/** Selective actor bytes $08-$3F plus XY history/index; no identity/progress/art/profile state. */
record NativeTeleportActorState(
        int x,
        int y,
        short xSub,
        short ySub,
        short xSpeed,
        short ySpeed,
        short inertia,
        short xRadius,
        short yRadius,
        int priority,
        int displayWidth,
        int mappingFrame,
        int animation,
        int animationFrame,
        int animationDuration,
        com.openggf.physics.Direction direction,
        boolean air,
        boolean rolling,
        boolean onObject,
        boolean rollingJump,
        boolean pushing,
        boolean inWater,
        boolean waterPhysicsActive,
        byte layer,
        boolean preventRespawn,
        boolean hurt,
        Integer routineOverride,
        byte angle,
        byte flipAngle,
        boolean flipTurned,
        int airLeft,
        boolean objectControlled,
        boolean allowsCpu,
        boolean suppressesMovement,
        boolean mappingControl,
        boolean shield,
        com.openggf.game.ShieldType shieldType,
        boolean shoes,
        boolean sliding,
        byte flipsRemaining,
        byte flipSpeed,
        int moveLock,
        int invulnerability,
        int invincibility,
        int shoeTime,
        boolean stickToConvex,
        boolean spindash,
        boolean pinball,
        boolean pinballLock,
        short spindashCounter,
        boolean jumping,
        int interact,
        int latchedId,
        boolean latchedReleased,
        boolean latchedBound,
        byte topSolidBit,
        byte lrbSolidBit,
        com.openggf.game.GroundMode groundMode,
        short[] xHistory,
        short[] yHistory,
        byte historyIndex) {
    NativeTeleportActorState { xHistory = xHistory.clone(); yHistory = yHistory.clone(); }
    @Override public short[] xHistory() { return xHistory.clone(); }
    @Override public short[] yHistory() { return yHistory.clone(); }
}
