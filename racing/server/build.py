#!/usr/bin/env python3
"""Build the racing server tools (master, dedicated host, verifier, bot/load/profile tools).

Usage:
  python3 racing/server/build.py                  # compile into target/racing-server/
  python3 racing/server/build.py --skip-engine    # reuse the engine build already in target/
  python3 racing/server/build.py --distribution   # also package target/racing-server/dist/
  target/racing-server/racing-server master --config master.yaml
  target/racing-server/racing-server verifier --master https://host:27900 --registration-token T --rom s3k.gen --data ./verifier-data
  target/racing-server/racing-server load-test --n 256 --duration 30 --mix adversarial
  target/racing-server/racing-server scale-test --rooms 4 --players 256 --duration 10 --warmup 3

The server is not part of the engine artifact. It compiles the Time Attack replay
implementation (racing/time-attack) and racing/server against the engine's shared networking
library, with Netty, Bouncy Castle and SQLite from the engine's test-scoped dependencies,
and writes a launcher whose classpath points at
target/classes, the compiled racing classes and the resolved dependency jars. The verifier embeds
the engine to replay attempts, so the engine build must match the clients' engine.
The optional distribution copies compiled classes/resources and the resolved dependency
jars, including the original version.properties, and runs without the checkout or Maven.

Origin: Time Attack extraction (docs/architecture/plans/2026-10-08-time-attack-mod-extraction.md).
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "target" / "racing-server"
TOOLS = {
    "master": "openggf.racing.server.master.MasterServerMain",
    "verifier": "openggf.racing.server.verifier.VerifierMain",
    "healthcheck": "openggf.racing.server.master.MasterHealthCheckMain",
    "deployment-smoke": "openggf.racing.server.tools.RacingDeploymentSmokeTool",
    "load-test": "openggf.racing.server.tools.GhostLoadTestTool",
    "socket-stress": "openggf.racing.server.tools.RacingSocketStressTool",
    "scale-test": "openggf.racing.server.tools.RacingScaleTool",
    "capture-video": "openggf.racing.server.tools.TimeAttackCapacityVideoTool",
    "capture-lobby": "openggf.racing.server.tools.TimeAttackLobbyVideoTool",
    "track-profiles": "openggf.racing.server.tools.TrackProfileExportTool",
}


def java_tool(tool):
    home = os.environ.get("JAVA_HOME")
    suffix = ".exe" if os.name == "nt" else ""
    return str(Path(home) / "bin" / (tool + suffix)) if home else tool


def launcher_source(runtime_cp, portable=False):
    """Keep tool selection identical in checkout and relocatable launchers."""
    cases = "\n".join(f'  {name}) main={main} ;;' for name, main in TOOLS.items())
    setup = ""
    if portable:
        # Resolve the installation, not the caller's working directory. Preserve cwd:
        # existing relative --config/--data/--rom arguments must retain their meaning.
        setup = '''app_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd) || exit 1
java=java
if [ -n "${JAVA_HOME:-}" ]; then java="$JAVA_HOME/bin/java"; fi
'''
        java = '"$java"'
        classpath = '"$app_dir/lib/racing-server.jar:$app_dir/lib/openggf-engine.jar:$app_dir/lib/deps/*"'
    else:
        java = shlex.quote(java_tool("java"))
        classpath = shlex.quote(runtime_cp)
    return f'''#!/bin/sh
# Generated by racing/server/build.py.
{setup}if [ "$#" -eq 0 ]; then
  echo "usage: racing-server <{'|'.join(TOOLS)}> [args...]" >&2; exit 2
fi
tool="$1"; shift
case "$tool" in
{cases}
  *) echo "usage: racing-server <{'|'.join(TOOLS)}> [args...]" >&2; exit 2 ;;
esac
exec {java} --enable-native-access=ALL-UNNAMED -cp {classpath} "$main" "$@"
'''


def sha256(path):
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def classes_jar(classes, destination):
    """Package only a compiled output tree, never the source checkout."""
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED) as jar:
        for path in sorted(classes.rglob("*")):
            if path.is_symlink():
                raise ValueError(f"Compiled output must not contain symlinks: {path}")
            if path.is_file():
                jar.write(path, path.relative_to(classes).as_posix())


def distribution_platform():
    machine = platform.machine().lower()
    arch = {"x86_64": "amd64", "aarch64": "arm64"}.get(machine, machine)
    return f"{platform.system().lower()}/{arch}"


def write_distribution(engine_classes, server_classes, dependencies, destination):
    """Build a self-contained runtime; preserve the compiled engine identity verbatim.

    The engine's test dependency closure is intentional: Netty, Bouncy Castle and
    SQLite currently live there. Do not infer a runtime closure by jar-name filtering.
    """
    version = engine_classes / "version.properties"
    if not version.is_file():
        raise ValueError(f"Missing compiled build identity: {version}; rebuild the engine")
    if destination.exists():
        shutil.rmtree(destination)
    (destination / "bin").mkdir(parents=True)
    (destination / "lib" / "deps").mkdir(parents=True)
    classes_jar(server_classes, destination / "lib" / "racing-server.jar")
    classes_jar(engine_classes, destination / "lib" / "openggf-engine.jar")
    # Indexes preserve distinct artifacts even when their filenames coincide.
    for index, dependency in enumerate(dependencies):
        dependency = Path(dependency)
        if dependency.suffix != ".jar" or not dependency.is_file():
            raise ValueError(f"Expected resolved dependency jar: {dependency}")
        shutil.copyfile(dependency, destination / "lib" / "deps" / f"{index:04d}-{dependency.name}")
    launcher = destination / "bin" / "racing-server"
    launcher.write_text(launcher_source(None, portable=True))
    launcher.chmod(0o755)
    manifest = {
        "formatVersion": 1,
        "buildPlatform": distribution_platform(),
        "versionPropertiesSha256": sha256(version),
        "files": {path.relative_to(destination).as_posix(): sha256(path)
                  for path in sorted(destination.rglob("*")) if path.is_file()},
    }
    (destination / "distribution.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Packaged {destination} ({manifest['buildPlatform']}); build identity preserved", flush=True)


def build(skip_engine=False, distribution=False):
    classpath_file = ROOT / "target" / "racing-server-classpath.txt"
    if not skip_engine or not classpath_file.exists():
        subprocess.run([sys.executable, "tools/testing/maven_queue.py", "-B", "-q", "-Dmse=off", "-DskipTests",
                        "compile", "dependency:build-classpath", "-Dmdep.includeScope=test",
                        f"-Dmdep.outputFile={classpath_file}"], cwd=ROOT, check=True)
    classes = OUT / "classes"
    if classes.exists():
        shutil.rmtree(classes)
    classes.mkdir(parents=True)
    deps = classpath_file.read_text().strip()
    compile_cp = os.pathsep.join([str(ROOT / "target" / "classes"), deps])
    sources = sorted(str(p) for root in ("racing/time-attack/src/main/java", "racing/server/src/main/java")
                     for p in (ROOT / root).rglob("*.java"))
    subprocess.run([java_tool("javac"), "--release", "25", "-nowarn", "-cp", compile_cp, "-d", str(classes),
                    *sources], check=True)
    shutil.copytree(ROOT / "racing/server/src/main/resources", classes, dirs_exist_ok=True)
    runtime_cp = os.pathsep.join([str(classes), str(ROOT / "target" / "classes"), deps])
    (OUT / "java-args.txt").write_text('--enable-native-access=ALL-UNNAMED\n-cp "' + runtime_cp.replace("\\", "/") + '"\n')
    if distribution:
        write_distribution(ROOT / "target" / "classes", classes,
                           [Path(p) for p in deps.split(os.pathsep) if p], OUT / "dist")
    if os.name == "nt":
        print(f'Built {classes}; run a tool with: "{java_tool("java")}" @"{OUT / "java-args.txt"}" <main class> [args...]')
        return
    launcher = OUT / "racing-server"
    launcher.write_text(launcher_source(runtime_cp))
    launcher.chmod(0o755)
    print(f"Built {launcher}", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--skip-engine", action="store_true", help="reuse the existing engine build in target/")
    parser.add_argument("--distribution", action="store_true", help="also create the relocatable runtime in target/racing-server/dist/")
    args = parser.parse_args()
    build(args.skip_engine, args.distribution)


if __name__ == "__main__":
    main()
